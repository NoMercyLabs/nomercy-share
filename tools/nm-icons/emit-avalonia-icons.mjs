// Emits the Moooom icons NoMercy Share uses as C# path data, taken from the designer's SVG files.
// Copied from Arcanum's tools/nm-icons/emit-avalonia-icons.mjs (namespace and header text changed).
// Source: nomercy-app-web resources/icons (the full Moooom set, one stroked 24-unit path per icon).
// The names come from icons.json next to the output; nothing is drawn by hand. Run it again when the list or the
// set changes:
//   node tools/nm-icons/emit-avalonia-icons.mjs <moooom icons folder> <icons.json> <output .cs>
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [iconsDir, listPath, outPath] = process.argv.slice(2);
if (!iconsDir || !listPath || !outPath) {
  console.error('usage: emit-avalonia-icons.mjs <moooom icons folder> <icons.json> <output .cs>');
  process.exit(2);
}

const names = JSON.parse(readFileSync(listPath, 'utf8')).icons;
const lines = [];
for (const name of [...names].sort()) {
  const svg = readFileSync(join(iconsDir, `${name}.svg`), 'utf8');
  const paths = [...svg.matchAll(/<path\b([^>]*)\/?>/g)].map(m => m[1]);
  // Arcanum draws one stroked path per icon; an icon of another shape is refused, never approximated.
  if (paths.length !== 1 || !/stroke="currentColor"/.test(paths[0]) || /<(circle|rect|line|polyline|polygon|ellipse)\b/.test(svg)) {
    console.error(`${name}: not a single stroked path; pick another Moooom icon`);
    process.exit(1);
  }
  const width = /stroke-width="([\d.]+)"/.exec(paths[0])?.[1];
  if (width !== '1.5' || !/viewBox="0 0 24 24"/.test(svg)) {
    console.error(`${name}: expected stroke-width 1.5 on a 24-unit view box`);
    process.exit(1);
  }
  const d = / d="([^"]+)"/.exec(paths[0])[1];
  lines.push(`        ["${name}"] = "${d}",`);
}

const out = `// <auto-generated>
// Generated by tools/nm-icons/emit-avalonia-icons.mjs from the Moooom icon set. Do not edit by hand.
// </auto-generated>

namespace NoMercy.Share.App.Icons;

/// <summary>The path data of the Moooom icons NoMercy Share uses (24-unit view box, stroke width 1.5).</summary>
internal static class MoooomIconData
{
    public static readonly IReadOnlyDictionary<string, string> Paths = new Dictionary<string, string>
    {
${lines.join('\n').replace(/,$/, '')}
    };
}
`;
writeFileSync(outPath, out);
console.log(`${names.length} icons written to ${outPath}`);
